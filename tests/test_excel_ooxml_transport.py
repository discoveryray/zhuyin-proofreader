def test_literal_writer_keeps_logical_seal_and_cell_attributes_until_wire(tmp_path):
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "待判定候選"
    text.append_text_row(sheet, ["review_id", "課本頁", "action"])
    text.append_text_row(sheet, ["row-one", "placeholder", None])
    original = sheet["B2"]
    original.font = Font(bold=True, color="112233")
    original.comment = Comment("same comment", "author")
    original.hyperlink = "https://example.invalid/source"
    style, comment, hyperlink = original._style, original._comment, original._hyperlink
    cell = text.write_text_value(sheet, 2, 2, "_x000D_")
    text.append_text_row(sheet, ["row-two", "_x005F_", None])
    assert cell is original and cell.comment.parent is cell
    assert cell.value == "_x000D_" and sheet["B3"].value == "_x005F_"
    assert cell._style is style and cell._comment is comment and cell._hyperlink is hyperlink
    logical = [{"review_id": "row-one", "課本頁": "_x000D_"},
               {"review_id": "row-two", "課本頁": "_x005F_"}]
    assert portable._excel_bound_rows(workbook, "expected") == logical
    path = tmp_path / "writer.xlsx"
    for _ in range(2):
        workbook.save(path)
        raw_sheet = XML.fromstring(members(path)["xl/worksheets/sheet1.xml"])
        wire = {node.get("r"): node.findtext(TAG + "is/" + TAG + "t")
                for node in raw_sheet.iter(TAG + "c")}
        assert wire["B2"] == "_x005F_x000D_" and wire["B3"] == "_x005F_x005F_"
        assert portable._excel_bound_rows(workbook, "expected") == logical
        with portable._read_excel_workbook(path) as read:
            assert portable._excel_bound_rows(read, "expected") == logical
    loaded = load_workbook(path)
    assert loaded.active["B2"].font.bold
    assert loaded.active["B2"].comment.text == "same comment"
    assert loaded.active["B2"].hyperlink.target == "https://example.invalid/source"
    loaded.close()
    cell.hyperlink = None  # Native Excel loader fills a blank linked cell with its URL.
    for value, kind in [(15, "n"), (None, "n"), ("=1+2", "f")]:
        cell.value = value
        assert cell.value == value and cell.data_type == kind
        workbook.save(path)
        loaded = load_workbook(path)
        assert loaded.active["B2"].value == value and loaded.active["B2"].data_type == kind
        loaded.close()
    workbook.close()


def test_expanded_transport_preserves_logical_capacity_without_truncation(tmp_path):
    original = "_x000D_" * 4681  # 32767 logical UTF-16 units, larger on the wire.
    workbook = Workbook()
    text.append_text_row(workbook.active, [original])
    assert workbook.active["A1"].value == original
    path = tmp_path / "capacity.xlsx"
    workbook.save(path)
    workbook.close()
    with portable._read_excel_workbook(path) as read:
        assert read.active["A1"].value == original
    assert len(XML.fromstring(members(path)["xl/worksheets/sheet1.xml"])
               .findtext(".//" + TAG + "t")) > 32767


ORIGINALS = ("_x000D_", "_x005F_", "=字_x000D_", "\t空白\r\n末行 ")



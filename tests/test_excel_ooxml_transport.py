NS = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"
TAG = "{" + NS + "}"
CT = "http://schemas.openxmlformats.org/package/2006/content-types"
REL = "http://schemas.openxmlformats.org/package/2006/relationships"
SST = "application/vnd.openxmlformats-officedocument.spreadsheetml.sharedStrings+xml"
RELTYPE = "http://schemas.openxmlformats.org/officeDocument/2006/relationships/sharedStrings"

# Hand-written transport/original pairs, never generated by the tested codec.
CASES = [
    ("\t空白_x000D_\n末行 ", "\t空白\r\n末行 "),
    ("第一行\n末行 ", "第一行\n末行 "),
    ("=1+2", "=1+2"),
    ("_x005F_x000D_", "_x000D_"),
    ("_x005F_x005F_", "_x005F_"),
    ("_x005f_x000D_", "_x000D_"),
    ("_x005F__x005F_x000D_", "__x000D_"),
    ("x005F_", "x005F_"),
    ("_x00G0_", "_x00G0_"),
    ("_xD83D__xDE00_", "😀"),
    ("_x005F_xD83D__x005F_xDE00_", "_xD83D__xDE00_"),
    ("_x0009_字_x000A_末_x000D_", "\t字\n末\r"),
]


def members(path):
    with ZipFile(path) as archive:
        return {name: archive.read(name) for name in archive.namelist()}


def write_members(path, payload):
    with ZipFile(path, "w", ZIP_DEFLATED) as archive:
        for name, raw in payload.items():
            archive.writestr(name, raw)


def shared_payload(payload, strings):
    content = XML.fromstring(payload["[Content_Types].xml"])
    XML.SubElement(content, "{" + CT + "}Override",
                   PartName="/xl/native-strings.xml", ContentType=SST)
    payload["[Content_Types].xml"] = XML.tostring(content)
    relationships = XML.fromstring(payload["xl/_rels/workbook.xml.rels"])
    XML.SubElement(relationships, "{" + REL + "}Relationship", Id="nativeStrings",
                   Type=RELTYPE, Target="native-strings.xml")
    payload["xl/_rels/workbook.xml.rels"] = XML.tostring(relationships)
    table = XML.Element(TAG + "sst")
    for string in strings:
        table.append(string)
    payload["xl/native-strings.xml"] = XML.tostring(table)


def raw_book(path, storage, *, raw=None, runs=None):
    workbook = Workbook()
    workbook.save(path)
    workbook.close()
    payload = members(path)
    sheet = XML.Element(TAG + "worksheet")
    XML.SubElement(sheet, TAG + "dimension", ref="A1:G4")
    data = XML.SubElement(sheet, TAG + "sheetData")
    row = XML.SubElement(data, TAG + "row", r="1")
    cell = XML.SubElement(row, TAG + "c", r="A1", t="inlineStr" if storage == "inline" else "s")
    string = XML.Element(TAG + "is" if storage == "inline" else TAG + "si")
    if runs is None:
        XML.SubElement(string, TAG + "t").text = raw
    else:
        for value in runs:
            run = XML.SubElement(string, TAG + "r")
            XML.SubElement(run, TAG + "t").text = value
        phonetic = XML.SubElement(string, TAG + "rPh", sb="0", eb="1")
        XML.SubElement(phonetic, TAG + "t").text = "not-visible"
    if storage == "inline":
        cell.append(string)
    else:
        XML.SubElement(cell, TAG + "v").text = "0"
        shared_payload(payload, [string])
    for coordinate, kind, value in [("B1", "n", "15"), ("C1", "n", "1.25"),
                                     ("D1", "b", "1"), ("E1", "n", None)]:
        native = XML.SubElement(row, TAG + "c", r=coordinate, t=kind)
        if value is not None:
            XML.SubElement(native, TAG + "v").text = value
    formula = XML.SubElement(row, TAG + "c", r="F1")
    XML.SubElement(formula, TAG + "f").text = "1+2"
    XML.SubElement(formula, TAG + "v").text = "3"
    cached = XML.SubElement(row, TAG + "c", r="G1", t="str")
    XML.SubElement(cached, TAG + "f").text = '"_x000D_"'
    XML.SubElement(cached, TAG + "v").text = "_x000D_"
    sparse = XML.SubElement(data, TAG + "row", r="4")
    XML.SubElement(XML.SubElement(sparse, TAG + "c", r="B4", t="n"), TAG + "v").text = "9"
    validation = XML.SubElement(sheet, TAG + "dataValidations", count="1")
    XML.SubElement(XML.SubElement(validation, TAG + "dataValidation", type="list", sqref="D1"),
                   TAG + "formula1").text = '"Y,N"'
    payload["xl/worksheets/sheet1.xml"] = XML.tostring(sheet)
    write_members(path, payload)
    return path


@pytest.mark.parametrize("storage", ["shared", "inline"])
@pytest.mark.parametrize("raw,original", CASES, ids=["crlf", "lf", "equals", "literal-cr",
    "literal-underscore", "lowerhex-underscore", "adjacent-escaped", "unprefixed",
    "malformed-looking-literal", "paired-surrogates", "literal-surrogates", "controls"])
def test_raw_transport_single_decode_and_native_cells(tmp_path, storage, raw, original):
    path = raw_book(tmp_path / "raw.xlsx", storage, raw=raw)
    before = path.read_bytes()
    for mode in (False, True):
        native = load_workbook(path, read_only=True, data_only=mode)
        baseline = list(native.active.values)
        native.close()
        workbook = text.load_text_workbook(path, data_only=mode)
        try:
            rows = list(workbook.active.values)
            assert rows[0][0] == original
            assert workbook.active["A1"].data_type == "s"
            assert rows[0][1:] == baseline[0][1:]
            assert rows[1:] == baseline[1:]
            assert workbook.read_only
        finally:
            workbook.close()
    assert path.read_bytes() == before
    assert b'dataValidation' in members(path)["xl/worksheets/sheet1.xml"]



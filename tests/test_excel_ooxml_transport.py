def native_shared_save(path):
    payload = members(path)
    strings = []
    for name in list(payload):
        if not name.startswith("xl/worksheets/") or not name.endswith(".xml"):
            continue
        sheet = XML.fromstring(payload[name])
        for cell in sheet.iter(TAG + "c"):
            if cell.get("t") != "inlineStr":
                continue
            inline = cell.find(TAG + "is")
            if inline is None:
                continue
            shared = copy.deepcopy(inline)
            shared.tag = TAG + "si"
            for value in shared.iter(TAG + "t"):
                if value.text is not None:
                    # Independent native-save lexical rule; no tested decoder
                    # creates either these bytes or the original-text oracle.
                    value.text = value.text.replace("\r", "_x000D_")
            cell.remove(inline)
            cell.set("t", "s")
            XML.SubElement(cell, TAG + "v").text = str(len(strings))
            strings.append(shared)
        payload[name] = XML.tostring(sheet)
    shared_payload(payload, strings)
    write_members(path, payload)


@pytest.mark.parametrize("lane", ["expected", "actual"])
@pytest.mark.parametrize("tamper", [False, True], ids=["import", "tamper"])
def test_formal_shared_literal_import_and_true_source_tamper(transport_pipeline, lane, tamper):
    root = transport_pipeline(lane)
    before_manifest = sp.json_load_strict(root / "校對工作階段.json")
    before_records = copy.deepcopy(before_manifest["records"])
    path, sheet_name = formal.exported(root, lane)
    workbook, sheet, columns = formal.fill(path, sheet_name, lane)
    if tamper:
        field = "所在行" if lane == "expected" else "sample_a_page"
        text.write_text_value(sheet, sheet.max_row, columns[field], "real changed protected source")
    workbook.save(path)
    workbook.close()
    native_shared_save(path)
    original_input = hashlib.sha256(path.read_bytes()).hexdigest()
    before = formal.project_bytes(root)
    importer = sp.import_gpt_decisions if lane == "expected" else sp.import_actual_gpt_decisions
    if tamper:
        with pytest.raises(ValueError):
            importer(root, path)
        assert formal.project_bytes(root) == before
    else:
        assert [row["printed_page"] for row in before_records] == list(ORIGINALS)
        assert importer(root, path)[0] == len(ORIGINALS)
        latest = sp.json_load_strict(root / "校對工作階段.json")
        db = sp.json_load_strict(root / "人工判定資料庫.json")
        ledger = sp.materialize_ledger(latest, db)
        assert [row["printed_page"] for row in ledger] == list(ORIGINALS)
        independent = ("actual", "actual_evidence") if lane == "expected" else ("expected_set", "expected_evidence")
        for key in independent:
            assert [row[key] for row in ledger] == [row[key] for row in before_records]
    assert hashlib.sha256(path.read_bytes()).hexdigest() == original_input
